// Natural Earth 1:50m land (via world-atlas TopoJSON, public domain) -> simplified rings for the globe.
// Writes src/data/land.js: rings as flat Int16 lists of lon,lat in tenths of a degree.
// Usage: node tools/make-land.mjs [tolerance_deg=0.12]
import { readFileSync, writeFileSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const SRC = join(ROOT, 'tools/land-50m.json');
const tol = Number(process.argv[2] || 0.12);
const raw = readFileSync(SRC, 'utf8');
const topo = JSON.parse(raw);
const { scale, translate } = topo.transform;

const arcs = topo.arcs.map((arc) => {
  let x = 0, y = 0;
  return arc.map(([dx, dy]) => {
    x += dx;
    y += dy;
    return [x * scale[0] + translate[0], y * scale[1] + translate[1]];
  });
});

function ringFromArcs(ids) {
  const out = [];
  for (const id of ids) {
    const a = id < 0 ? arcs[~id].slice().reverse() : arcs[id];
    for (let i = out.length ? 1 : 0; i < a.length; i++) out.push(a[i]);
  }
  return out;
}

// Douglas–Peucker on lon/lat degrees.
function simplify(pts, eps) {
  if (pts.length < 4) return pts;
  const keep = new Uint8Array(pts.length);
  keep[0] = keep[pts.length - 1] = 1;
  const stack = [[0, pts.length - 1]];
  while (stack.length) {
    const [a, b] = stack.pop();
    let dmax = 0, idx = -1;
    const [ax, ay] = pts[a], [bx, by] = pts[b];
    const dx = bx - ax, dy = by - ay;
    const len = Math.hypot(dx, dy);
    for (let i = a + 1; i < b; i++) {
      // A closed ring starts and ends on one point: measure from that point instead of a zero-length segment.
      const d = len < 1e-9 ? Math.hypot(pts[i][0] - ax, pts[i][1] - ay) : Math.abs(dy * pts[i][0] - dx * pts[i][1] + bx * ay - by * ax) / len;
      if (d > dmax) {
        dmax = d;
        idx = i;
      }
    }
    if (dmax > eps && idx > 0) {
      keep[idx] = 1;
      stack.push([a, idx], [idx, b]);
    }
  }
  return pts.filter((_, i) => keep[i]);
}

function area(r) {
  let s = 0;
  for (let i = 0; i < r.length; i++) {
    const [x1, y1] = r[i], [x2, y2] = r[(i + 1) % r.length];
    s += x1 * y2 - x2 * y1;
  }
  return Math.abs(s / 2);
}

const rings = [];
for (const g of topo.objects.land.geometries) {
  const polys = g.type === 'Polygon' ? [g.arcs] : g.arcs;
  for (const poly of polys) {
    for (const ringIds of poly) {
      const r = simplify(ringFromArcs(ringIds), tol);
      if (r.length >= 4 && area(r) > 0.08) rings.push(r);
    }
  }
}
let points = 0;
const enc = rings.map((r) => {
  points += r.length;
  return r.flatMap(([x, y]) => [Math.round(x * 10), Math.round(y * 10)]);
});
const sha = createHash('sha256').update(raw).digest('hex');
const js = `// Generated by tools/make-land.mjs from Natural Earth 1:50m land (world-atlas land-50m.json).
// Natural Earth: public domain. ${rings.length} rings, ${points} points, Douglas–Peucker tolerance ${tol}°.
// Values: lon,lat pairs in tenths of a degree.
export const LAND_SOURCE = { source: 'Natural Earth 1:50m land, via world-atlas TopoJSON', version: 'land-50m.json', license: 'Public domain (Natural Earth); world-atlas packaging ISC', checksum: 'sha256:${sha}', resolution: '1:50m simplified to ${tol}°' };
export const LAND = ${JSON.stringify(enc)};
`;
writeFileSync(join(ROOT, 'src/data/land.js'), js);
console.log(`land.js: ${rings.length} rings, ${points} points, ${(js.length / 1024).toFixed(0)} KB, source sha256 ${sha.slice(0, 12)}`);
