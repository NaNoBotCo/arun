// Protection map for #wonder: the E02 wetland run at every position the page can set
// (0.00–1.00 in steps of 0.01 on both axes, 10,201 runs) for the default storm, packed into
// src/wonder/protection-map.data.js. The page recomputes any position live and compares.
//
//   node tools/protection-map.mjs [--workers 7]        compute (about 1 hour on an 8-core laptop), then pack
//   node tools/protection-map.mjs --from <dir>         pack the JSON files a previous run wrote to <dir>
//
// Unchanged kernel, unchanged defaults: if either changes, rerun this, or the page shows the map as not applying.

import { Worker, isMainThread, parentPort, workerData } from 'node:worker_threads';
import { writeFileSync, readFileSync, mkdirSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import os from 'node:os';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const KERNEL = join(ROOT, 'src/kernels/e02.js');
const SCEN = join(ROOT, 'src/core/scenario.js');
const P = 101;

function arg(k) {
  const i = process.argv.indexOf(k);
  return i >= 0 ? process.argv[i + 1] : null;
}

async function compute(outDir, W) {
  const { defaultScenario } = await import(SCEN);
  const { makeRegion, createSim, METHOD_VERSION } = await import(KERNEL);
  const s = defaultScenario();
  const region = makeRegion(s.seed, s.hydro.grid, s.region.cellSize_m);
  const t0 = performance.now();
  const base = createSim(region, s.hydro, false, { snapshots: false });
  base.runToEnd();
  const baseRun = { hotelSeconds: base.state.assets[0].secondsAbove, peakQ: base.state.peakQ, ms: performance.now() - t0 };
  const n = P * P;
  const hotel = new Float64Array(n), peakQ = new Float64Array(n), stored = new Float64Array(n), ms = new Float64Array(n);
  let done = 0, next = 0, cpu = 0;
  const wall0 = Date.now();
  await new Promise((resolve) => {
    let live = 0;
    for (let w = 0; w < W; w++) {
      const wk = new Worker(fileURLToPath(import.meta.url), { workerData: { s } });
      live++;
      const feed = () => wk.postMessage(next < n ? next++ : -1);
      wk.on('message', (m) => {
        if (m.ready) return feed();
        hotel[m.i] = m.hotel;
        peakQ[m.i] = m.peakQ;
        stored[m.i] = m.stored;
        ms[m.i] = m.ms;
        cpu += m.ms;
        done++;
        if (done % 250 === 0) console.log(new Date().toISOString().slice(11, 19), done, '/', n, 'cpu h', (cpu / 3.6e6).toFixed(2));
        feed();
      });
      wk.on('exit', () => {
        if (--live === 0) resolve();
      });
    }
  });
  const meta = { method: METHOD_VERSION, seed: s.seed, hydro: s.hydro, grid: s.hydro.grid, positions: n, step: 0.01, workers: W, wallSeconds: (Date.now() - wall0) / 1000, cpuHours: cpu / 3.6e6, machine: os.cpus()[0].model + ' × ' + os.cpus().length, node: process.version, at: new Date().toISOString(), base: baseRun };
  mkdirSync(outDir, { recursive: true });
  writeFileSync(join(outDir, 'meta.json'), JSON.stringify(meta, null, 2));
  writeFileSync(join(outDir, 'hotel_seconds.json'), JSON.stringify(Array.from(hotel)));
  writeFileSync(join(outDir, 'peakQ.json'), JSON.stringify(Array.from(peakQ, (v) => Math.round(v * 1000) / 1000)));
  writeFileSync(join(outDir, 'stored.json'), JSON.stringify(Array.from(stored, (v) => Math.round(v))));
  writeFileSync(join(outDir, 'ms.json'), JSON.stringify(Array.from(ms, (v) => Math.round(v))));
  return outDir;
}

// Hotel seconds above threshold are whole multiples of the 10 s timestep: stored as seconds / 10.
// Peak outflow stored in tenths of m³/s. Both fit Uint16.
function pack(dir) {
  const meta = JSON.parse(readFileSync(join(dir, 'meta.json'), 'utf8'));
  const hotel = JSON.parse(readFileSync(join(dir, 'hotel_seconds.json'), 'utf8'));
  const peakQ = JSON.parse(readFileSync(join(dir, 'peakQ.json'), 'utf8'));
  const step = meta.hydro.timestep_s;
  const h16 = Uint16Array.from(hotel, (v) => {
    const k = Math.round(v / step);
    if (Math.abs(k * step - v) > 1e-6 || k > 65535) throw new Error('hotel seconds not a whole number of steps: ' + v);
    return k;
  });
  const q16 = Uint16Array.from(peakQ, (v) => {
    const k = Math.round(v * 10);
    if (k > 65535) throw new Error('peak flow out of range: ' + v);
    return k;
  });
  const b64 = (a) => Buffer.from(a.buffer, a.byteOffset, a.byteLength).toString('base64');
  const m = {
    method: meta.method, seed: meta.seed, hydro: meta.hydro, positions: meta.positions, step: meta.step,
    machine: meta.machine, workers: meta.workers, wallSeconds: Math.round(meta.wallSeconds), cpuHours: Math.round(meta.cpuHours * 100) / 100, at: meta.at,
    baseHotelSeconds: meta.base.hotelSeconds, basePeakQ: Math.round(meta.base.peakQ * 10) / 10,
  };
  const src = `// Generated by tools/protection-map.mjs on ${meta.at}. Do not edit by hand.
// E02 (${meta.method}) wetland run at every position 0.00–1.00 step 0.01, default storm, seed ${meta.seed}.
// hotel: seconds above 0.2 m / ${step}, peakQ: tenths of m³/s, little-endian Uint16, index = row * 101 + column.
export const PMAP_META = ${JSON.stringify(m)};
export const PMAP_HOTEL = '${b64(h16)}';
export const PMAP_PEAKQ = '${b64(q16)}';
`;
  const out = join(ROOT, 'src/wonder/protection-map.data.js');
  writeFileSync(out, src);
  console.log('wrote', out, (src.length / 1024).toFixed(0), 'KB');
}

if (isMainThread) {
  const from = arg('--from');
  if (from) pack(from);
  else pack(await compute(join(ROOT, 'team/ots/protection-map-raw'), Number(arg('--workers') || Math.max(1, os.cpus().length - 1))));
} else {
  const { makeRegion, createSim } = await import(KERNEL);
  const s = workerData.s;
  const region = makeRegion(s.seed, s.hydro.grid, s.region.cellSize_m);
  parentPort.on('message', (i) => {
    if (i < 0) return process.exit(0);
    const x = (i % P) / 100, y = Math.floor(i / P) / 100;
    const t = performance.now();
    const sim = createSim(region, { ...s.hydro, interventionX: x, interventionY: y }, true, { snapshots: false });
    sim.runToEnd();
    parentPort.postMessage({ i, hotel: sim.state.assets[0].secondsAbove, peakQ: sim.state.peakQ, stored: sim.budget().stored, ms: performance.now() - t });
  });
  parentPort.postMessage({ ready: true });
}
