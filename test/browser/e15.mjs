// E15 interaction check: run, view switch, tile click, failure case, sweep, export record.
import { launch, openPage } from './browser.mjs';
import { mkdirSync } from 'node:fs';
import { join } from 'node:path';
const out = process.argv[2] || join(process.env.TMPDIR || '/tmp', 'arun-e15');
mkdirSync(out, { recursive: true });
const { browser } = await launch();
const { page, errors, requests } = await openPage(browser, 'e15');
const fail = [];
const expect = (c, m) => { if (!c) fail.push(m); };
await page.waitForTimeout(2500);
const yearB0 = await page.inputValue('[data-name="yearB"] input[type=number]');
await page.waitForTimeout(2500);
const yearB1 = await page.inputValue('[data-name="yearB"] input[type=number]');
expect(yearB0 !== yearB1, 'playback did not advance the year');
await page.click('button.run');
await page.click('button:has-text("Flags vs truth")');
await page.mouse.click(300, 400);
await page.fill('[data-name="yearB"] input[type=number]', '2025');
await page.dispatchEvent('[data-name="yearB"] input[type=number]', 'change');
await page.waitForTimeout(600);
const f1 = await page.textContent('.metric[data-name="f1"] .mv');
expect(parseFloat(f1) > 0.8, 'preset F1 low: ' + f1);
await page.screenshot({ path: join(out, 'e15-detect.png') });
await page.click('button:has-text("Show failure case")');
await page.waitForTimeout(1500);
const f1b = await page.textContent('.metric[data-name="f1"] .mv');
expect(parseFloat(f1b) < 0.5, 'failure F1 not low: ' + f1b);
const msg = await page.textContent('.e15-status');
expect(/fails/.test(msg), 'no failure message: ' + msg);
await page.screenshot({ path: join(out, 'e15-failure.png') });
await page.click('button:has-text("PCA colour")');
await page.waitForTimeout(300);
await page.screenshot({ path: join(out, 'e15-pca.png') });
await page.click('button:has-text("Back to preset")');
await page.waitForTimeout(1500);
await page.press('canvas.stage-canvas >> nth=0', 'ArrowRight');
await page.click('button:has-text("Add selected tile")');
await page.click('button:has-text("Run noise sweep")');
await page.waitForTimeout(2500);
const note = await page.textContent('.e15-btns:has(button:has-text("Run noise sweep"))');
expect(/ms/.test(note), 'sweep did not finish: ' + note);
await page.click('[role=tab]:has-text("Export")');
await page.waitForTimeout(300);
const txt = await page.textContent('.export');
expect(/valid against schema/.test(txt), 'run record not valid');
console.log(fail.length ? 'FAIL ' + fail.join(' | ') : 'ok interactions', 'errors=' + errors.length, 'outside=' + requests.length);
for (const e of errors) console.log(e);
await browser.close();
process.exit(fail.length || errors.length ? 1 : 0);
