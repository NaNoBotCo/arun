// E13 interaction check: tap adds a sample, Run adds suggested sensors, failure cases, export record.
import { launch, openPage } from './browser.mjs';
import { mkdirSync } from 'node:fs';
import { join } from 'node:path';
const out = process.argv[2] || join(process.env.TMPDIR || '/tmp', 'arun-e13');
mkdirSync(out, { recursive: true });
const { browser } = await launch();
const { page, errors, requests } = await openPage(browser, 'e13');
const fail = [];
const expect = (c, m) => { if (!c) fail.push(m); };
const tile = (n) => page.textContent(`.metric[data-name="${n}"] .mv`);
await page.waitForTimeout(2500);
expect((await tile('n')) === '24', 'start n ' + (await tile('n')));
const rmse0 = parseFloat(await tile('rmse'));
const box = await page.locator('canvas.stage-canvas').first().boundingBox();
await page.mouse.click(box.x + box.width * 0.5, box.y + box.height * 0.6);
await page.waitForTimeout(900);
expect((await tile('n')) === '25', 'tap did not add a sample: ' + (await tile('n')));
await page.click('button.run');
await page.waitForTimeout(3500);
await page.click('button.run');
expect(parseInt(await tile('n')) > 27, 'run did not add sensors: ' + (await tile('n')));
await page.screenshot({ path: join(out, 'e13-run.png') });
await page.click('button:has-text("Failure case: too long")');
await page.waitForTimeout(1200);
expect(/not justified/.test(await tile('unc')), 'long l not refused: ' + (await tile('unc')));
await page.click('button:has-text("Uncertainty") >> nth=0');
await page.waitForTimeout(300);
await page.screenshot({ path: join(out, 'e13-fail.png') });
await page.click('button:has-text("Failure case: clustered")');
await page.waitForTimeout(1200);
expect(/one corner/.test(await page.textContent('.e13-status')), 'no cluster note');
await page.click('[role=tab]:has-text("Export")');
await page.waitForTimeout(300);
expect(/valid/.test(await page.textContent('.tabpane.export')), 'record not valid');
console.log(fail.length ? 'FAIL ' + fail.join('; ') : 'ok', 'errors', errors.length, errors.join('|'), 'outside', requests.length);
await browser.close();
process.exit(fail.length || errors.length ? 1 : 0);
