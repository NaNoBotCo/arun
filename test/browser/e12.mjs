// E12 interaction check: growth, click select, failure case, compare, export record.
import { launch, openPage } from './browser.mjs';
import { mkdirSync } from 'node:fs';
import { join } from 'node:path';
const out = process.argv[2] || join(process.env.TMPDIR || '/tmp', 'arun-e12');
mkdirSync(out, { recursive: true });
const { browser } = await launch();
const { page, errors, requests } = await openPage(browser, 'e12');
const fail = [];
const expect = (c, m) => { if (!c) fail.push(m); };
const tile = (n) => page.textContent(`.metric[data-name="${n}"] .mv`);
await page.waitForTimeout(2500);
const gap0 = parseFloat(await tile('gap'));
expect(gap0 < 2, 'golden gap too big: ' + gap0);
const box = await page.locator('canvas.stage-canvas').first().boundingBox();
await page.mouse.click(box.x + box.width / 2 + 60, box.y + box.height / 2 + 30);
expect(/n = \d+/.test(await tile('selected')), 'select text');
await page.click('button:has-text("Failure case")');
await page.waitForTimeout(300);
const gap1 = parseFloat(await tile('gap'));
expect(gap1 > 3 * gap0, `120 deg gap ${gap1} vs ${gap0}`);
expect(/fraction|rays|turn/.test(await page.textContent('.e12-status')) || /rays/.test(await page.textContent('.e12-status')), 'no failure note');
await page.selectOption('[data-name="compare"] select', '137.5');
await page.waitForTimeout(300);
await page.screenshot({ path: join(out, 'e12-fail-compare.png') });
await page.click('button:has-text("Golden angle")');
await page.fill('[data-name="amp"] input[type=number]', '0.4');
await page.dispatchEvent('[data-name="amp"] input[type=number]', 'change');
await page.waitForTimeout(300);
await page.screenshot({ path: join(out, 'e12-mod.png') });
await page.click('[role=tab]:has-text("Export")');
await page.waitForTimeout(300);
expect(/valid/.test(await page.textContent('.tabpane.export')), 'record not valid');
console.log(fail.length ? 'FAIL ' + fail.join('; ') : 'ok', 'errors', errors.length, 'outside', requests.length);
await browser.close();
process.exit(fail.length || errors.length ? 1 : 0);
