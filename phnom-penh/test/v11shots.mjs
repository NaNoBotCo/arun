// Screenshots of the ARUN 11 views at phone size: node test/v11shots.mjs [file] [outDir]
import { chromium } from 'playwright-core';
import { createServer } from 'node:http';
import { readFileSync, mkdirSync } from 'node:fs';
const file = process.argv[2] || 'dist/arun-phnom-penh.html', outDir = process.argv[3] || 'test/results/v11/shots';
mkdirSync(outDir, { recursive: true });
const srv = createServer((q, r) => { r.writeHead(200, { 'content-type': 'text/html' }); r.end(readFileSync(file)); }).listen(0);
const base = `http://localhost:${srv.address().port}/`;
const exe = `${process.env.HOME}/Library/Caches/ms-playwright/chromium-1228/chrome-mac-arm64/Google Chrome for Testing.app/Contents/MacOS/Google Chrome for Testing`;
const browser = await chromium.launch({ executablePath: exe, args: ['--use-angle=metal', '--enable-gpu', '--ignore-gpu-blocklist'] });
const ctx = await browser.newContext({ viewport: { width: 390, height: 844 }, deviceScaleFactor: 2, hasTouch: true, isMobile: true });
const page = await ctx.newPage(); const errs = [];
page.on('pageerror', e => errs.push(e.message)); page.on('console', m => { if (m.type() === 'error') errs.push(m.text()); });
await page.goto(base + '?nointro&lang=' + (process.env.L || 'en'));
await page.waitForFunction(() => window.__ready || window.__error, null, { timeout: 60000 });
const shot = async n => { await page.waitForTimeout(500); await page.screenshot({ path: `${outDir}/${n}.png` }); };
await shot('01-observe');
await page.evaluate(() => window.__CTX.openLens('discover', 'discover')); await shot('02-discover');
await page.evaluate(() => { window.__CTX.closeLens(); window.__CTX.setView('build'); window.__CTX.setTool('gauge'); }); await shot('03-build-tool');
await page.touchscreen.tap(150, 330); await page.waitForTimeout(300); await shot('04-build-preview');
await page.click('.pending .btn.go'); await shot('05-build-done');
await page.evaluate(() => window.__CTX.setView('compare')); await shot('06-compare-forecast');
await page.click('text=' + (await page.evaluate(() => document.querySelector('.cmp .btn.go').textContent)));
await page.waitForFunction(() => document.querySelector('.cmpT'), null, { timeout: 120000 }); await shot('07-compare-scored');
await page.evaluate(() => { window.__CTX.setView('observe'); window.__CTX.openLens('evidence', 'c4'); }); await shot('08-evidence');
await page.evaluate(() => { document.querySelector('#sheetBody').scrollTop = 700; }); await shot('09-evidence-2');
await page.evaluate(() => window.__CTX.setView('notebook')); await shot('10-notebook');
await page.evaluate(() => window.__CTX.openLens('wrong', 'wrong')); await shot('11-wrong');
await page.evaluate(() => window.__CTX.openLens('machine', 'machine')); await shot('12-machine');
await page.evaluate(() => window.__CTX.openLens('shores', 'shores')); await shot('13-shores');
await page.evaluate(() => window.__CTX.openLens('invisible', 'invisible')); await shot('14-invisible');
await page.evaluate(() => window.__CTX.openLens('ordinary', 'ordinary')); await shot('15-ordinary');
console.log('errors', JSON.stringify(errs));
await browser.close(); srv.close();
