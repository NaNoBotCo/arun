const STATUS_TEXT = {
  MATHEMATICAL: 'Pure mathematics. No data about the world goes in.',
  SYNTHETIC: 'Seeded fictional data made by this code. It describes no real place, person or business.',
  PUBLIC_HISTORICAL: 'Public historical data with its licence and version.',
  RESEARCH_MODEL: 'Output of a published research model, version pinned.',
  AUTHORIZED_AGGREGATE: 'Coarse totals released by a data owner under an agreement.',
};

const injectedCss = new Set();

export function injectCss(id, css) {
  if (!css || injectedCss.has(id)) return;
  injectedCss.add(id);
  document.head.append(h('style', { dataset: { ex: id } }, css));
}

// Build the ctx handed to mount(). Tracks loops and jobs so destroy() releases them.
export function makeCtx({ compact = false, initial = null } = {}) {
  const loops = [];
  const jobs = new Set();
  const cleanups = [];
  const ctx = {
    scenario,
    ui,
    chart,
    compact,
    initial,
    announce,
    reducedMotion,
    rng: (seed, label) => makeRng(label ? deriveSeed(seed, label) : seed),
    loop(frame) {
      const l = createLoop(frame);
      l.onError = (e) => announce('Stopped: ' + e.message, 'error');
      loops.push(l);
      return l;
    },
    runJob(name, payload, opts = {}) {
      const handle = runJob(name, payload, opts);
      jobs.add(handle);
      handle.promise.finally(() => jobs.delete(handle)).catch(() => {});
      return handle;
    },
    onCleanup(fn) {
      cleanups.push(fn);
    },
    _dispose() {
      for (const l of loops) l.dispose();
      for (const j of jobs) j.cancel();
      for (const f of cleanups) {
        try {
          f();
        } catch {}
      }
    },
  };
  return ctx;
}

function methodPanel(meta) {
  const inputsTable = meta.inputs.length
    ? h('table', { class: 'dtable' },
        h('thead', {}, h('tr', {}, ['Input', 'Range', 'Default', 'Unit'].map((c) => h('th', { scope: 'col' }, c)))),
        h('tbody', {}, meta.inputs.map((i) => h('tr', {},
          h('td', {}, i.label),
          h('td', {}, i.options ? i.options.map((o) => o.label).join(' · ') : i.type === 'toggle' ? 'on / off' : `${fmt(i.min, 4)} – ${fmt(i.max, 4)}`),
          h('td', {}, i.options ? String((i.options.find((o) => o.value === i.default) || {}).label ?? i.default) : String(i.default)),
          h('td', {}, i.unit || '')))))
    : null;
  return h('div', { class: 'tabpane method' },
    h('div', { class: 'prose', html: meta.method }),
    h('dl', { class: 'facts' },
      h('dt', {}, 'Method version'), h('dd', {}, h('code', {}, meta.methodVersion)),
      h('dt', {}, 'Seeds'), h('dd', {}, meta.seedStrategy || '—'),
      h('dt', {}, 'Reads from'), h('dd', {}, meta.dependencies.length ? meta.dependencies.map((d) => h('a', { href: '#' + d.toLowerCase() }, d + ' ')) : 'Nothing; stands alone.'),
      h('dt', {}, 'Feeds'), h('dd', {}, (meta.feeds || []).length ? meta.feeds.map((d) => h('a', { href: '#' + d.toLowerCase() }, d + ' ')) : 'No other exhibit reads its results.')),
    inputsTable ? h('h4', {}, 'Inputs') : null,
    inputsTable ? h('div', { class: 'scrollx' }, inputsTable) : null);
}

function limitsPanel(meta) {
  return h('div', { class: 'tabpane limits' },
    h('h4', {}, 'Data status'),
    h('p', {}, statusTag(meta.dataStatus), ' ', STATUS_TEXT[meta.dataStatus] || ''),
    h('h4', {}, 'Limits'),
    h('ul', {}, meta.limitations.map((l) => h('li', {}, l))),
    h('h4', {}, t('frame.whoPays')),
    meta.whoPays
      ? h('dl', { class: 'facts' },
          h('dt', {}, 'Buyer'), h('dd', {}, meta.whoPays.buyer),
          h('dt', {}, 'Pays for'), h('dd', {}, meta.whoPays.why),
          h('dt', {}, 'Shared benefit, once validated and permitted'), h('dd', {}, meta.whoPays.benefit))
      : h('p', {}, t('frame.research')),
    h('h4', {}, 'Sources'),
    meta.provenance.length
      ? h('ul', {}, meta.provenance.map((p) => h('li', {}, `${p.source} · ${p.version} · ${p.license}`, p.attribution ? ` · ${p.attribution}` : '')))
      : h('p', {}, 'Generated by this code; no outside data.'));
}

export function renderExhibit(root, mod, { compact = false } = {}) {
  const meta = mod.meta;
  injectCss(meta.id, mod.css);
  const replayRecord = takeReplay(meta.id);
  const ctx = makeCtx({ compact, initial: replayRecord ? { inputs: replayRecord.inputs, seed: replayRecord.seed } : null });

  const stage = h('div', { class: 'ex-stage', dataset: { ex: meta.id } });
  const controls = h('div', { class: 'ex-controls' });
  const metrics = h('div', { class: 'ex-metrics' });
  const footer = h('div', { class: 'ex-footer' });

  if (compact) {
    const wrap = h('div', { class: 'ex compact', dataset: { ex: meta.id } }, stage, h('div', { class: 'ex-compact-side' }, controls, metrics));
    root.replaceChildren(wrap);
    const inst = mod.mount({ stage, controls, metrics, footer }, ctx);
    return {
      instance: inst,
      destroy() {
        try {
          inst && inst.destroy && inst.destroy();
        } finally {
          ctx._dispose();
        }
      },
    };
  }

  const tabs = ['play', 'method', 'limits', 'export'];
  const tabBtns = {};
  const panes = {};
  const tablist = h('div', { class: 'tabs', role: 'tablist', 'aria-label': 'Exhibit panel' });
  const exportPane = h('div', { class: 'tabpane export' });
  panes.play = h('div', { class: 'tabpane play' }, controls, metrics, footer);
  panes.method = methodPanel(meta);
  panes.limits = limitsPanel(meta);
  panes.export = exportPane;
  const panelBody = h('div', { class: 'panel-body' });
  for (const k of tabs) {
    const b = h('button', { type: 'button', role: 'tab', id: `tab-${meta.id}-${k}`, 'aria-selected': String(k === 'play'), 'aria-controls': `pane-${meta.id}-${k}` }, t('frame.' + k));
    b.addEventListener('click', () => select(k));
    b.addEventListener('keydown', (e) => {
      const i = tabs.indexOf(k);
      if (e.key === 'ArrowRight' || e.key === 'ArrowDown') {
        e.preventDefault();
        select(tabs[(i + 1) % tabs.length], true);
      } else if (e.key === 'ArrowLeft' || e.key === 'ArrowUp') {
        e.preventDefault();
        select(tabs[(i + tabs.length - 1) % tabs.length], true);
      }
    });
    tabBtns[k] = b;
    tablist.append(b);
    panes[k].id = `pane-${meta.id}-${k}`;
    panes[k].setAttribute('role', 'tabpanel');
    panes[k].setAttribute('aria-labelledby', b.id);
    panes[k].hidden = k !== 'play';
    panelBody.append(panes[k]);
  }
  let inst = null;
  function select(k, focus) {
    for (const x of tabs) {
      tabBtns[x].setAttribute('aria-selected', String(x === k));
      tabBtns[x].tabIndex = x === k ? 0 : -1;
      panes[x].hidden = x !== k;
    }
    if (focus) tabBtns[k].focus();
    if (k === 'export') fillExport();
  }
  for (const x of tabs) tabBtns[x].tabIndex = x === 'play' ? 0 : -1;

  const exportOut = h('div', { class: 'export-out' });
  let currentRecord = null;
  function fillExport() {
    exportPane.replaceChildren();
    if (!inst || !inst.getRecord) {
      exportPane.append(h('p', {}, 'Nothing to export yet.'));
      return;
    }
    const run = inst.getRecord();
    const rec = buildRunRecord(meta, run);
    const v = validateRunRecord(rec);
    currentRecord = rec;
    const json = JSON.stringify(rec, null, 2);
    const base = `arun-${meta.id}-seed${rec.seed}`;
    const formats = [
      ['Run record · JSON', () => exportPanel(exportOut, { filename: base + '.json', mime: 'application/json', text: json, note: v.ok ? 'Checked against run-record schema 1.0: valid.' : 'Schema problems: ' + v.errors.join('; ') })],
      ['Metrics · CSV', () => exportPanel(exportOut, { filename: base + '-metrics.csv', mime: 'text/csv', text: recordToCSV(rec) })],
    ];
    if (inst.getTable) {
      formats.push(['Series · CSV', () => {
        const tb = inst.getTable();
        exportPanel(exportOut, { filename: base + '-series.csv', mime: 'text/csv', text: toCSV(tb.columns, tb.rows), note: `${tb.rows.length} rows. Text cells that start like a formula get a leading apostrophe.` });
      }]);
    }
    if (inst.getReport) {
      formats.push(['Report · HTML', () => {
        const rep = inst.getReport();
        exportPanel(exportOut, { filename: base + '-report.html', mime: 'text/html', text: rep, note: 'A single self-contained HTML file. Opens offline.' });
      }]);
    }
    const fmtRow = h('div', { class: 'btnrow' }, formats.map(([label, fn]) => button(label, fn, { kind: 'small' })));
    exportPane.append(
      h('p', { class: 'small' }, v.ok ? '✓ Run record valid against schema 1.0.' : '✗ ' + v.errors.join('; ')),
      fmtRow,
      h('div', { class: 'btnrow' },
        button('Save to Compare', () => {
          saveRun(rec);
          announce(`Saved ${meta.id} run to Compare.`);
        }, { kind: 'small' })),
      replayRecord ? reproCheck(replayRecord, rec) : null,
      exportOut);
    formats[0][1]();
  }

  function reproCheck(saved, now) {
    const rows = compareMetrics(saved.metrics, now.metrics);
    const allSame = rows.every((r) => r.same);
    return h('div', { class: 'repro ' + (allSame ? 'ok' : 'diff') },
      h('h4', {}, allSame ? 'Reproduced: every metric matches the saved run' : 'Differs from the saved run'),
      h('p', { class: 'small muted' }, `Saved ${saved.runId}. Tolerance: relative 1e-9.`),
      h('div', { class: 'scrollx' }, h('table', { class: 'dtable' },
        h('thead', {}, h('tr', {}, ['Metric', 'Saved', 'Now', ''].map((c) => h('th', {}, c)))),
        h('tbody', {}, rows.map((r) => h('tr', {}, h('td', {}, r.name), h('td', {}, fmt(r.a, 6)), h('td', {}, fmt(r.b, 6)), h('td', {}, r.same ? '✓' : '≠')))))));
  }

  const share = button(t('frame.share'), () => {
    const url = location.href.split('#')[0] + '#' + meta.id.toLowerCase();
    copyText(url).then((ok) => ok && announce(t('frame.copied')));
  }, { kind: 'ghost small' });

  const head = h('header', { class: 'ex-head' },
    h('a', { href: '#lab', class: 'back' }, '← ', t('frame.back')),
    h('div', { class: 'ex-titles' },
      h('span', { class: 'ex-id' }, meta.id, ' · ', meta.priority),
      h('h1', {}, exTitle(meta.id, meta.title)),
      meta.subtitle ? h('span', { class: 'ex-sub' }, meta.subtitle) : null),
    h('div', { class: 'ex-tags' }, statusTag(meta.dataStatus), share));

  const replayBanner = replayRecord
    ? h('div', { class: 'replay-banner', role: 'status' }, `Replaying saved run ${replayRecord.runId.slice(0, 24)}… with seed ${replayRecord.seed}. Run it, then open Export to check the numbers.`)
    : null;

  const page = h('section', { class: 'ex', dataset: { ex: meta.id } },
    head,
    replayBanner,
    h('div', { class: 'ex-body' },
      stage,
      h('aside', { class: 'ex-panel', 'aria-label': 'Controls and notes' }, tablist, panelBody)));
  root.replaceChildren(page);
  try {
    inst = mod.mount({ stage, controls, metrics, footer }, ctx);
  } catch (e) {
    console.error(e);
    stage.replaceChildren(h('div', { class: 'ex-error', role: 'alert' }, `${meta.id} failed to start: ${e.message}`));
  }
  return {
    instance: inst,
    meta,
    destroy() {
      try {
        inst && inst.destroy && inst.destroy();
      } finally {
        ctx._dispose();
      }
    },
    currentRecord: () => currentRecord,
  };
}

export { STATUS_TEXT, STATUS_LABEL };
